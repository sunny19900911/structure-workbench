import test from 'node:test';
import assert from 'node:assert/strict';
import {fixture} from './fixture.mjs';
import {inspectPptPackage} from '../../../server/office-ppt-package.mjs';
test('native PPT HTTP command, immutable history, download, conflict and reopen',async t=>{
 const f=await fixture();t.after(f.close);
 const get=async action=>(await fetch(f.base+'/'+action)).json();
 const command=(expectedRevision,command)=>fetch(f.base+'/command',{method:'POST',headers:{'X-Workbench-Request':'office-documents','Content-Type':'application/json'},body:JSON.stringify({expectedRevision,command})});
 let loaded=await get('view');const shape=loaded.view.slides[0].shapes[0];
 let response=await command(1,{op:'shape.text',slide:1,shapeId:shape.id,expectedText:shape.text,text:'结构方案调整稿\n教学楼'});assert.equal(response.status,200);
 assert.equal((await response.json()).document.fileRevision,2);
 response=await command(1,{op:'slide.delete',slide:1});assert.equal(response.status,409);
 response=await command(2,{op:'shape.geometry',slide:1,shapeId:shape.id,expectedGeometry:Object.fromEntries(['x','y','width','height'].map(k=>[k,shape[k]])),x:1000000,y:1200000,width:8000000,height:1000000});assert.equal(response.status,200);
 response=await command(3,{op:'slide.duplicate',slide:1});assert.equal(response.status,200);
 response=await command(4,{op:'slide.move',slide:2,to:3});assert.equal(response.status,200);
 loaded=await get('view');assert.equal(loaded.document.fileRevision,5);assert.equal(loaded.view.slides.length,3);
 assert.equal(loaded.view.slides[2].shapes[0].text,'结构方案调整稿\n教学楼');
 const exported=Buffer.from(await(await fetch(f.base+'/content')).arrayBuffer());const reopened=await inspectPptPackage(exported,'pptx');
 assert.equal(reopened.slides[0].shapes[0].x,1000000);assert.equal(reopened.slides[0].shapes[0].height,1000000);
 const old=Buffer.from(await(await fetch(f.base+'/content?revision=1')).arrayBuffer());assert.deepEqual(old,f.original);
 assert.equal((await get('history')).versions.length,5);
 const concurrent=await Promise.all([command(5,{op:'slide.add',slide:1}),command(5,{op:'slide.add',slide:1})]);assert.deepEqual(concurrent.map(r=>r.status).sort(),[200,409]);
 const invalid=await command(6,{op:'shape.format',slide:1,shapeId:shape.id,color:'red'});assert.equal(invalid.status,422);assert.equal((await get('view')).document.fileRevision,6);
 const restore=(expectedRevision,revision,header=true)=>fetch(f.origin+'/api/office-ppt-history/'+f.record.projectId+'/'+f.record.documentId,{method:'POST',headers:header?{'X-Workbench-Request':'office-documents'}:{},body:JSON.stringify({expectedRevision,revision})});
 assert.equal((await restore(6,1,false)).status,403);
 assert.equal((await restore(5,1)).status,409);
 assert.equal((await restore(6,99)).status,400);
 assert.equal((await restore(6,1)).status,200);
 assert.deepEqual(Buffer.from(await(await fetch(f.base+'/content')).arrayBuffer()),f.original);
 assert.equal((await restore(7,6)).status,200);
 assert.equal((await get('view')).view.slides.length,4);
});
