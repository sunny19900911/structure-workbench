import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const preview = await readFile(path.join(repo, 'data', 'general-note-01-preview-template.html'));
// Browser generation starts from the untouched converted 604 master. The
// project-specific cleanup is applied at generation time so a changed project
// profile can re-evaluate optional clauses instead of inheriting a stale copy.
const docx = await readFile(path.join(repo, 'data', 'general-note-01-template.docx'));

const output = [
  '/* Generated by scripts/build-general-note-browser-assets.mjs. */',
  `window.GN7_GENERAL_PREVIEW_BASE64=${JSON.stringify(preview.toString('base64'))};`,
  `window.GN7_GENERAL_DOCX_BASE64=${JSON.stringify(docx.toString('base64'))};`,
  '',
].join('\n');

await writeFile(path.join(repo, 'data', 'general-note-01-assets.js'), output, 'utf8');
console.log(JSON.stringify({
  previewBytes: preview.length,
  docxBytes: docx.length,
  assetBytes: Buffer.byteLength(output),
}, null, 2));
