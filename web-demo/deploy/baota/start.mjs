import {createServer} from 'node:http';
import {fileURLToPath} from 'node:url';
import {resolve,join} from 'node:path';
import {existsSync} from 'node:fs';
import {mkdir,readFile} from 'node:fs/promises';
import {createApplication} from './http-app.mjs';
import {deepSeekLocalApi,calculationBookLocalApi} from '../../vite.config.js';
import {expansionApi} from '../../server/expansion-api.mjs';
import {projectStoreApi} from '../../server/project-store.mjs';
import {intakeApi} from '../../server/intake-api.mjs';
import {calculationPdfApi} from '../../server/calculation-pdf-api.mjs';
import {regulationDiscoveryApi} from '../../server/regulation-discovery-api.mjs';
import {decisionResearchApi} from '../../server/decision-research-api.mjs';
import {rewriteApi} from '../../deepseek-rewrite/service.mjs';
import {localDeepSeekConfig} from '../../server/local-deepseek-config.mjs';
const root=fileURLToPath(new URL('../../',import.meta.url));process.chdir(root);
if(existsSync('.env'))process.loadEnvFile('.env');
const env=localDeepSeekConfig(process.env);
const deployment=existsSync('deployment.json')?JSON.parse(await readFile('deployment.json','utf8')):{};
const basePath=deployment.basePath||'/';
env.WORKBENCH_DATABASE_ROOT||=resolve(root,'../workbench-data');
env.WORKBENCH_PROJECT_STORE||=join(env.WORKBENCH_DATABASE_ROOT,'projects');
env.CALCBOOK_SOURCE_DIR||=join(env.WORKBENCH_DATABASE_ROOT,'calculation-sources');
env.CALCBOOK_PYTHON||=env.WORKBENCH_PYTHON||'python3';
await mkdir(env.WORKBENCH_PROJECT_STORE,{recursive:true});
const app=createApplication({publicDir:join(root,'dist'),basePath,user:env.WORKBENCH_USER,password:env.WORKBENCH_PASSWORD,plugins:[deepSeekLocalApi(env),calculationBookLocalApi(env),expansionApi(env),projectStoreApi(env),intakeApi(env),calculationPdfApi(env),regulationDiscoveryApi(),decisionResearchApi(env),rewriteApi(env)]});
createServer(app).listen(Number(env.PORT||5190),'127.0.0.1',()=>console.log('工作台已启动：http://127.0.0.1:'+Number(env.PORT||5190)+basePath));
